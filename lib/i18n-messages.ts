export type UiLang = "en" | "zh-CN";
export const DICTIONARIES: Readonly<Record<UiLang, Record<MessageKey, string>>> = { en, "zh-CN": zh };
export const UI_LANG_KEY = "spectre-scribe:ui-lang";

export type Vars = Record<string, string | number>;

export function translate(lang: UiLang, key: MessageKey, vars?: Vars): string {
  const template = DICTIONARIES[lang][key] ?? en[key];
  return vars ? template.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : template;
}

export function defaultUiLang(navigatorLang: string | undefined): UiLang {
  return navigatorLang?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

